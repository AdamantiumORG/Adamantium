/// The nearest `f64` representation of pi for floating-point calculations.
pub const PI_F64: f64 = std::f64::consts::PI;

/// Returns the sine of `value` radians.
pub fn sin(value: f64) -> f64 {
    value.sin()
}

/// Returns the cosine of `value` radians.
pub fn cos(value: f64) -> f64 {
    value.cos()
}

/// Returns the tangent of `value` radians.
pub fn tan(value: f64) -> f64 {
    value.tan()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pi_contains_exactly_3255_ascii_characters() {
        assert_eq!(PI.len(), 3_255);
        assert!(PI.is_ascii());
        assert!(PI.starts_with("3.14159265358979323846264338327950288419716939937510"));
        assert!(PI[2..].bytes().all(|byte| byte.is_ascii_digit()));
    }

    #[test]
    fn trigonometric_functions_use_radians() {
        let epsilon = 1e-12;
        assert!((sin(PI_F64 / 2.0) - 1.0).abs() < epsilon);
        assert!((cos(PI_F64) + 1.0).abs() < epsilon);
        assert!((tan(PI_F64 / 4.0) - 1.0).abs() < epsilon);
    }
}
